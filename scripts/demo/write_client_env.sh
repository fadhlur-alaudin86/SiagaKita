#!/usr/bin/env bash
# write_client_env.sh - Generate the CLIENT-ONLY build config for the demo droplet.
#
# Purpose: Produce one small file teammates can use to build all three Flutter
#          clients against the exhibition droplet. Safe to share: it contains
#          public endpoints only, never credentials.
# Data & Logic Flow: droplet IP -> env/demo.env -> passed to every client with
#          --dart-define-from-file.
# Key Components: env/demo.env, consumed by mobile-flutter, mobile-flutter-responder,
#          and windows_console_flutter.
#
# Why five keys and not two: the clients read different variables.
#   - mobile-flutter and windows_console_flutter: API_BASE_URL, WS_BASE_URL
#   - mobile-flutter-responder: API_HOST, API_PORT, WS_PORT (it composes
#     "http://$API_HOST:$API_PORT/api/v1" itself and has no API_BASE_URL support)
# Emitting both sets lets one file build all three clients.
#
# Usage:
#   ./scripts/demo/write_client_env.sh <droplet-ip> [output-file]
set -euo pipefail

IP="${1:?usage: write_client_env.sh <droplet-ip> [output-file]}"
PORT="${PORT:-80}"
OUT="${2:-env/demo.env}"

[[ "$IP" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || {
  echo "ERROR: '$IP' does not look like an IPv4 address." >&2
  exit 1
}

mkdir -p "$(dirname "$OUT")"

cat > "$OUT" <<EOF
# SiagaKita - exhibition demo client build config.
#
# This file is safe to share: it contains public endpoints only. It holds NO
# secrets. Never substitute the server-side infrastructure/.env.prod, which
# carries the database password, JWT secret, Gmail OAuth tokens, and the Firebase
# service-account private key.
#
# Generated by scripts/demo/write_client_env.sh for droplet $IP on $(date -u +%Y-%m-%dT%H:%M:%SZ).
#
# Usage from the repository root:
#   cd mobile-flutter            && flutter build apk --release --dart-define-from-file=../env/demo.env
#   cd mobile-flutter-responder  && flutter build apk --release --dart-define-from-file=../env/demo.env
#   cd windows_console_flutter   && flutter build linux --release --dart-define-from-file=../env/demo.env
#
# Bind to API/WS base URLs (mobile-flutter, windows_console_flutter)
API_BASE_URL=http://$IP:$PORT/api/v1
WS_BASE_URL=ws://$IP:$PORT/v1/ws/connect
# Bind to host/port (mobile-flutter-responder)
API_HOST=$IP
API_PORT=$PORT
WS_PORT=$PORT
EOF

echo "Wrote $OUT"
echo "  API base : http://$IP:$PORT/api/v1"
echo "  WebSocket: ws://$IP:$PORT/v1/ws/connect"
